"""
This Sphinx extension aims to include generated images or data to be included in Sphinx documents,
such as CSV files generated by a script calling an API.
"""

from importlib.metadata import version

from sphinx.application import Sphinx
from sphinx.util.typing import ExtensionMetadata

from sphinxcontrib.exec_to_file.domain import ExecToFileDomain


def setup(app: Sphinx) -> ExtensionMetadata:
    """Register the domain of the extension."""
    ExecToFileDomain.register(app)
    return {
        "version": version("sphinx-exec-to-file"),
        "parallel_read_safe": True,
        "parallel_write_safe": True,
    }
